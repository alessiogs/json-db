import type { Collection } from "../atoms/jsonAtom"
import { readCell, type Row } from "./schema"

/** The contents of an exported db.json: rows keyed by collection name. */
export type DbJson = Record<string, Row[]>

/** Plain rows for every collection, keyed by collection name. */
export const toDbJson = (collections: readonly Collection[]): DbJson =>
  Object.fromEntries(
    collections.map((collection): [string, Row[]] => [
      collection.name,
      collection.data,
    ])
  )

/** A PascalCase type name for a collection, e.g. "book-genres" -> "BookGenres". */
export const typeName = (name: string): string => {
  const joined = name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")
  return joined === "" || /^[0-9]/.test(joined) ? `_${joined}` : joined
}

/** A key as-is when it is a valid identifier, otherwise a quoted string. */
const propertyKey = (key: string): string =>
  /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key)

/** One `export type` for a collection's rows; `id` is always a required string. */
const rowType = (collection: Collection): string => {
  const fields = collection.schema
    .filter((column) => column.key !== "id")
    .map((column) => {
      const required = collection.data.every(
        (row) => readCell(row, column).status === "valid"
      )
      return `  ${propertyKey(column.key)}${required ? "" : "?"}: ${column.kind}`
    })

  return [
    `export type ${typeName(collection.name)} = {`,
    "  id: string",
    ...fields,
    "}",
  ].join("\n")
}

/** A TypeScript file describing the rows of every collection. */
export const toTypeScript = (collections: readonly Collection[]): string => {
  const db =
    collections.length === 0
      ? "export type Db = {}"
      : [
          "export type Db = {",
          ...collections.map(
            (collection) =>
              `  ${propertyKey(collection.name)}: ${typeName(collection.name)}[]`
          ),
          "}",
        ].join("\n")

  return (
    [
      "// Generated by JSON DB",
      ...collections.map(rowType),
      db,
    ].join("\n\n") + "\n"
  )
}

/** Save `contents` as a file by clicking a temporary download link. */
export const download = (
  filename: string,
  contents: string,
  type: string
): void => {
  const url = URL.createObjectURL(new Blob([contents], { type }))
  const link = document.createElement("a")
  link.href = url
  link.download = filename
  document.body.append(link)
  link.click()
  link.remove()
  // Revoke after the click has started the download; some browsers need the delay.
  setTimeout(() => URL.revokeObjectURL(url), 0)
}
